  // A UTC timestamp made from LOCAL calendar parts avoids DST-length days.
  // The same local date selects the same joke on every visit. Rotation repeats after 31 days.
  function dayNumber(date) {
    return Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000);
  }
  function render() {
    const now = new Date();
    const text = document.getElementById('daily-joke');
    const label = document.getElementById('joke-date');
    if (!text || !label) return;
    text.textContent = jokes[((dayNumber(now) % jokes.length) + jokes.length) % jokes.length];
    label.textContent = new Intl.DateTimeFormat('ru-RU', {day: 'numeric', month: 'long', year: 'numeric'}).format(now);
    label.dateTime = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
  }
  let timer;
  function schedule() {
    clearTimeout(timer);
    render();
    const now = new Date();
    const midnight = new Date(now.getFullYear(), now.getMonth(), now.getDate() + 1);
    timer = setTimeout(schedule, midnight.getTime() - now.getTime() + 100);
  }
  schedule();
  document.addEventListener('visibilitychange', () => {
    if (!document.hidden) schedule();
  });
